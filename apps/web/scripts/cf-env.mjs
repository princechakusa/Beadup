// Before a Cloudflare build: copy the public `vars` from wrangler.jsonc into
// .env.production.local, so `next build` inlines the same NEXT_PUBLIC_* values
// the Worker gets at runtime. One source of truth, nothing secret in it.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const jsonc = readFileSync(join(root, "wrangler.jsonc"), "utf8");
// Strip // comments (not inside strings) and trailing commas.
const json = jsonc
  .split("\n")
  .map((line) => line.replace(/^(\s*)\/\/.*$/, "$1").replace(/(".*?"|[^"\s])\s+\/\/.*$/, "$1"))
  .join("\n")
  .replace(/,(\s*[}\]])/g, "$1");
const { vars = {} } = JSON.parse(json);

const lines = Object.entries(vars)
  .filter(([k]) => k.startsWith("NEXT_PUBLIC_"))
  .map(([k, v]) => `${k}=${v}`);
writeFileSync(join(root, ".env.production.local"), `# Generated by scripts/cf-env.mjs from wrangler.jsonc\n${lines.join("\n")}\n`);
console.log(`cf-env: wrote ${lines.length} public vars`);
