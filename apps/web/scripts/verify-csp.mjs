// Post-build guard for the nonce-based CSP (see src/lib/csp.ts).
// The prerendered shells are served without a nonce, so they may contain only
// inline scripts whose hash is allow-listed, and no inline styles at all.
// Fails the build if a Next/React upgrade or a code change breaks that.
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

// fileURLToPath, not URL.pathname: the latter breaks on Windows ("/C:/...", %20).
const root = fileURLToPath(new URL("..", import.meta.url));
const allowed = new Set(JSON.parse(readFileSync(join(root, "src/lib/csp-hashes.json"), "utf8")).script);
const dir = join(root, ".next/server/app");

function* html(d) {
  for (const name of readdirSync(d)) {
    const p = join(d, name);
    if (statSync(p).isDirectory()) yield* html(p);
    else if (name.endsWith(".html")) yield p;
  }
}

// Next's built-in static 500 page (served only if rendering itself crashes).
// It is generated by the framework from its own error component and can't be
// customised; under the CSP its inline styles and scripts are blocked, so it
// shows as plain text. Our app/global-error.tsx handles errors at runtime.
const SKIP = new Set(["_global-error.html"]);

const problems = [];
let files = 0;
for (const file of html(dir)) {
  if (SKIP.has(file.slice(dir.length + 1))) continue;
  files++;
  const doc = readFileSync(file, "utf8");
  for (const m of doc.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g)) {
    const [, attrs, body] = m;
    if (/\bsrc=/.test(attrs) || /\bnonce=/.test(attrs) || body.length === 0) continue;
    const hash = `sha256-${createHash("sha256").update(body).digest("base64")}`;
    if (!allowed.has(hash)) problems.push(`${file}: inline script ${hash} (${body.slice(0, 60)}...)`);
  }
  for (const m of doc.matchAll(/<style\b([^>]*)>/g)) {
    if (!/\bnonce=/.test(m[1])) problems.push(`${file}: inline <style> without nonce`);
  }
  for (const m of doc.matchAll(/<[a-zA-Z][^>]*\sstyle="[^"]*"/g)) {
    problems.push(`${file}: style attribute: ${m[0].slice(0, 100)}`);
  }
}

// No prerendered HTML is the strictest case: every page renders per request with a nonce.
if (files === 0) console.log("CSP check: no prerendered shells (all pages render per request).");
if (problems.length) {
  console.error("CSP check failed. The static shells must not need 'unsafe-inline':\n" + problems.join("\n"));
  process.exit(1);
}
console.log(`CSP check: ${files} prerendered shells, no un-hashed inline scripts or inline styles.`);
